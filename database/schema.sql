-- Final AVERIS schema reference; source of truth is database/migrations/.
CREATE TABLE public.organizations (
 id VARCHAR(36) PRIMARY KEY, name VARCHAR(120) NOT NULL, slug VARCHAR(160) NOT NULL UNIQUE,
 invite_code VARCHAR(48) NOT NULL UNIQUE, created_at TIMESTAMP WITHOUT TIME ZONE NOT NULL
);
CREATE TABLE public.users (
 id VARCHAR(36) PRIMARY KEY, organization_id VARCHAR(36) NOT NULL REFERENCES public.organizations(id),
 full_name VARCHAR(100) NOT NULL, email VARCHAR(254) NOT NULL UNIQUE, password_hash VARCHAR(512) NOT NULL,
 role VARCHAR(20) NOT NULL DEFAULT 'owner', is_active BOOLEAN NOT NULL DEFAULT TRUE,
 created_at TIMESTAMP WITHOUT TIME ZONE NOT NULL
);
CREATE TABLE public.auth_sessions (
 token_hash VARCHAR(64) PRIMARY KEY, user_id VARCHAR(36) NOT NULL REFERENCES public.users(id),
 created_at TIMESTAMP WITHOUT TIME ZONE NOT NULL, expires_at TIMESTAMP WITHOUT TIME ZONE NOT NULL,
 revoked_at TIMESTAMP WITHOUT TIME ZONE NULL
);
CREATE TABLE public.workspace_snapshots (
 organization_id VARCHAR(36) PRIMARY KEY REFERENCES public.organizations(id), data JSON NOT NULL,
 revision INTEGER NOT NULL DEFAULT 0, updated_at TIMESTAMP WITHOUT TIME ZONE NOT NULL,
 updated_by VARCHAR(36) NOT NULL REFERENCES public.users(id)
);
CREATE TABLE public.server_audit_events (
 id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 organization_id VARCHAR(36) NOT NULL REFERENCES public.organizations(id),
 actor_id VARCHAR(36) NOT NULL REFERENCES public.users(id), action VARCHAR(80) NOT NULL,
 details JSON NOT NULL, created_at TIMESTAMP WITHOUT TIME ZONE NOT NULL
);
CREATE TABLE public.erp_business_records (
 id VARCHAR(36) PRIMARY KEY, organization_id VARCHAR(36) NOT NULL REFERENCES public.organizations(id),
 collection VARCHAR(40) NOT NULL, record_key VARCHAR(80) NOT NULL, payload JSON NOT NULL,
 created_at TIMESTAMP WITHOUT TIME ZONE NOT NULL, updated_at TIMESTAMP WITHOUT TIME ZONE NOT NULL,
 created_by VARCHAR(36) NOT NULL REFERENCES public.users(id), updated_by VARCHAR(36) NOT NULL REFERENCES public.users(id),
 CONSTRAINT uq_erp_org_collection_key UNIQUE (organization_id, collection, record_key)
);
CREATE UNIQUE INDEX uq_erp_org_product_sku
  ON public.erp_business_records (organization_id, upper(btrim(payload ->> 'sku')))
  WHERE collection = 'products' AND NULLIF(btrim(payload ->> 'sku'), '') IS NOT NULL;
CREATE INDEX ix_organizations_slug ON public.organizations (slug);
CREATE INDEX ix_organizations_invite_code ON public.organizations (invite_code);
CREATE INDEX ix_users_organization_id ON public.users (organization_id);
CREATE INDEX ix_users_email ON public.users (email);
CREATE INDEX ix_auth_sessions_user_id ON public.auth_sessions (user_id);
CREATE INDEX ix_auth_sessions_expires_at ON public.auth_sessions (expires_at);
CREATE INDEX ix_server_audit_events_organization_id ON public.server_audit_events (organization_id);
CREATE INDEX ix_server_audit_events_actor_id ON public.server_audit_events (actor_id);
CREATE INDEX ix_workspace_snapshots_updated_by ON public.workspace_snapshots (updated_by);
CREATE INDEX ix_erp_business_records_organization_id ON public.erp_business_records (organization_id);
CREATE INDEX ix_erp_business_records_collection ON public.erp_business_records (collection);
CREATE INDEX ix_erp_business_records_created_by ON public.erp_business_records (created_by);
CREATE INDEX ix_erp_business_records_updated_by ON public.erp_business_records (updated_by);
