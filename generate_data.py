def generate(c,seed):
    r=random.Random(seed);ps=people(c["patients"],r)
    return {"people":ps,"tasks":tasks(c["tasks"],ps,r),"appointments":appointments(c["appointments"],ps,r),"resources":resources(c["resources"],r),"workforce":workforce(c["workforce"],r),"diagnostics":diagnostics(c["diagnostics"],ps,r),"pharmacy":pharmacy(c["pharmacy"],r),"medications":medications(c.get("medications",len(ps)),ps,r),"finance":finance(c["finance"],ps,r),"messages":messages(c["messages"],ps,r),"incidents":incidents(c["incidents"],r),"reports":reports(c["reports"],r)}
def validate(d):
    errors=[];warnings=[];ids=set();ps={x["id"] for x in d["people"]}
    for table,rows in d.items():
        for row in rows:
            if not row.get("id"): errors.append(table+" missing id")
            elif row["id"] in ids: errors.append("duplicate "+row["id"])
            else: ids.add(row["id"])
    for table in ["tasks","appointments","diagnostics","finance","messages"]:
        for row in d[table]:
            if row.get("person_id") not in ps: errors.append(table+" broken person reference")
    for row in d["pharmacy"]:
        if row["quantity"]<0 or row["minimum"]<0: errors.append("negative inventory "+row["id"])
        if row["quantity"]<row["minimum"]: warnings.append("low stock "+row["id"])
    return errors,warnings
def write_json(d,p): p.write_text(json.dumps(d,indent=2),encoding="utf-8")
def write_csv(d,p):
    p.mkdir(parents=True,exist_ok=True)
    for table,rows in d.items():
        fields=sorted({k for row in rows for k in row})
        with (p/(table+".csv")).open("w",newline="",encoding="utf-8") as f:
            w=csv.DictWriter(f,fieldnames=fields);w.writeheader();w.writerows(rows)
